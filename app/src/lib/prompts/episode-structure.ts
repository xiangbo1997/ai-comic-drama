/**
 * 爆款短剧方法论 Prompt 层（单一真源）
 *
 * 规则来源：抖音漫剧平台数据 + 红果编剧课 + cinemetrics 动漫剪辑镜长研究 +
 * 竞品拆解，蒸馏为可直接注入 LLM 的中文 prompt 文本块。由两条叙事管线共享：
 *   (A) 小说解析路径：script-parse.ts / agent-prompts/script-parser.ts
 *   (B) 短剧创作路径：agent-prompts/drama-script.ts / storyboard-table.ts
 *
 * 设计原则：
 * - 只导出可组合的常量块 + 极小工具函数；由各消费者自行决定拼哪几块。
 * - 结尾钩子规则「无条件」适用（含第 1 集），从源头治「凑时长」。
 * - 钩子五分类与 types/series-bible.ts 的 HOOK_TYPES 对齐，供史官读取。
 */

/** 剧本层 — 开场钩子规则（0-3s 抓人是漫剧留存的生死线） */
export const EPISODE_HOOK_RULES = `【开场钩子（0-3 秒决定留存，最高优先级）】
- 第一个分镜必须是本集冲突最高点或悬念最强的画面（高潮前置 / 危机进行时 / 极端反差），严禁：风景空镜开场、起床 / 走路等日常铺垫、旁白介绍世界观、"从前有个人"式顺叙。
- 第一句台词必须制造信息差或认知冲突（身份悖论 / 极端羞辱 / 威胁 / 反常识宣言），禁止自我介绍与背景说明。
- 开场 10 秒内安排 3-5 个分镜（快切建立紧张感）。
- 首场景出场角色 ≤3 人。`;

/** 剧本层 — 节奏规则（爽点密度 + 打脸公式 + 台词密度） */
export const EPISODE_PACING_RULES = `【节奏骨架（每一秒都要有信息增量）】
- 节奏骨架：0-3s 钩住 → ~6s 进入冲突 → ~10s 抛出悬念 → ~30s 第一个爽点 → 60s 内完成一次情绪爆发（打脸 / 逆袭 / 揭秘）→ 结尾 10-15s 设下集钩子。
- 每 15-20 秒一个小高潮或新信息增量；每 30 秒一个剧情爆点；禁止信息真空（连续分镜无新信息）。
- 打脸四步公式：羞辱 → 隐忍藏锋（可埋 1 个隐藏实力提示镜头）→ 反击亮身份 → 爽感释放（围观者震惊反应镜头收尾）。
- 台词密度 12-18 句 / 分钟，单句 ≤15 字口语化短句；每个反转场景配一句可独立传播的金句。`;

/** 剧本层 — 结尾钩子规则（无条件适用，含第 1 集；从五类钩子选一并轮换） */
export const EPISODE_ENDING_RULES = `【结尾钩子（每集必须留钩，含第 1 集）】
- 每集最后一镜必须停在未解决的张力上：从五类钩子选一——悬念钩（关键疑问不答）/ 反转钩（最后一刻颠覆）/ 情绪钩（情绪推顶后切断）/ 信息钩（关键信息只说一半）/ 危机钩（突发威胁）。
- 若系列上下文提供了「近 N 集钩子类型」，本集必须选用不同类型（连续 3 集禁同型）。
- 下一集开头不得立即完全化解上集钩子。`;

/**
 * 剧本层 — 冲突升级方法论（矛盾四级阶梯 + 股价级反转三式 + 反同质化）
 *
 * 蒸馏自 Toonflow 故事骨架 / 改编策略技能：短剧是情绪产品，冲突要有阶梯、
 * 反转要预埋、桥段要反套路。把「结构层为好卖打地基」的规则灌进解析/创作层，
 * 治两类通病——只堆吵架不升级矛盾、无预埋的凭空反转、照搬烂大街桥段。
 */
export const EPISODE_CONFLICT_RULES = `【冲突升级（矛盾要有阶梯，反转要预埋，桥段要反套路）】
- 矛盾四级阶梯（每集主冲突至少到第 2 级，高潮集用 3-4 级）：① 基础对立（欲望 vs 阻碍成立但弱）→ ② 强化二选一（强欲望 + 强阻碍 + 不可调和的两难困境）→ ③ 高级立场冲突（两个好人因不同选择走向不同命运，是立场冲突而非善恶冲突，没有绝对好坏人）→ ④ 升级不可逆后果（主角为解初始矛盾的行动招致更严重、回不了头的代价）。矛盾是内在「想要而得不到」，冲突是外在对抗行为——先把矛盾抬到阶梯上，别只靠堆吵架打斗撑戏。
- 股价级反转三式（从根上打破「刚看开头就猜到结尾」）：① 预期误导（全程不藏信息，只用观众思维定式引导出「合理的错误结论」）② 人设颠覆（只能用在配角，绝不动主角核心底色，否则观众弃剧）③ 动机置换（同一行为同时完美适配表层/深层两个动机，前后逻辑不崩）。铁律：反转必须提前预埋线索，揭晓时观众能回想起伏笔、旧线索严丝合缝；禁止无预埋的凭空反转、空降硬凹结局；单集反转 ≤1 次；反转 ≠ 钩子（钩子是断点悬而未决，反转是对已知的颠覆）。
- 反同质化：市面烂大街的套路（赘婿被辱、当众摊牌亮身份、闪婚霸总、认亲胎记、三个巴掌等出现 >10 次的桥段）不得原样照搬，必须至少做一处变形——换动机 / 换场域 / 换代价，否则同质化桥段 = 同质化剧本。`;

/** 分镜层 — 单镜时长与镜头节奏纪律（治「凑时长」的源头规则） */
export const SHOT_RHYTHM_RULES = `【单镜节奏（短切是常态，禁止凑时长）】
- 单镜默认 2-4 秒（对话 1.5-2s、动作 1-2s、情绪特写 2-3s）；超过 5 秒必须有明确叙事理由；一个长动作宁可拆成 建立镜 → 动作镜 → 反应镜。
- duration 如实按叙事需要填写（1-60s）：系统会按视频模型能力自动分段衔接，绝对禁止为凑总时长而拉长单镜。
- 反转 / 揭秘瞬间用急推特写（dolly_in / zoom_in）；钩子镜用 zoom_in 定格；高潮附近镜头更短更密。
- 景别以近景 / 特写为主（竖屏），特写用于情绪反应和关键道具；相邻分镜避免同景别同机位。`;

/**
 * 组合出「剧本层」方法论块（开场 + 节奏 + 结尾 + 冲突升级），可选追加分镜层节奏纪律。
 * 消费者决定是否包含 SHOT_RHYTHM_RULES（解析路径需要，创作路径按需）。
 * includeConflict 默认 true——冲突升级是剧本层通用方法论，与开场/节奏/结尾并列必备。
 */
export function buildEpisodeStructureBlock(opts?: {
  includeShotRhythm?: boolean;
  includeConflict?: boolean;
}): string {
  const includeConflict = opts?.includeConflict ?? true;
  const blocks = [
    EPISODE_HOOK_RULES,
    EPISODE_PACING_RULES,
    EPISODE_ENDING_RULES,
  ];
  if (includeConflict) blocks.push(EPISODE_CONFLICT_RULES);
  if (opts?.includeShotRhythm) blocks.push(SHOT_RHYTHM_RULES);
  return blocks.join("\n\n");
}
